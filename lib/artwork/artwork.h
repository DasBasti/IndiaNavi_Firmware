#ifndef ARTWORK_H_
#define ARTWORK_H_

#include <stdint.h>

#include "display.h"

/*
 * Ink a where the bit (y & 3) * 4 + (x & 3) of mask is set, else ink b. The pattern is anchored
 * at the screen pixel, like the patterns of the vector map.
 */
typedef struct {
    uint8_t a;
    uint8_t b;
    uint16_t mask;
} artwork_paint_t;

/*
 * The pixels row by row as runs: byte = paint << 4 | n, n = 1..15 pixels, or n = 0 and the next
 * byte + 16 pixels. Paint 0 is transparent. Generated by tools/generate_searching_image.py.
 */
typedef struct {
    uint16_t width;
    uint16_t height;
    const artwork_paint_t* paints;
    uint8_t paint_count;
    const uint8_t* data;
    uint32_t data_size;
} artwork_t;

/* shown on the map screen until the position is known */
extern const artwork_t searching_position_artwork;

/* Draws the picture with its top left corner at left/top, it is decoded while it is drawn */
error_code_t artwork_draw(const display_t* dsp, const artwork_t* art, int16_t left, int16_t top);

#endif /* ARTWORK_H_ */
